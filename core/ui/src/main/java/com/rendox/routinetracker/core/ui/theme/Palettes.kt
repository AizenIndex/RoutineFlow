fun ColorScheme.applyAmoledOverride(isDark: Boolean, isAmoled: Boolean): ColorScheme {
    return if (isDark && isAmoled) {
        this.copy(
            background = Color.Black,
            surface = Color.Black,
            surfaceVariant = Color(0xFF121212),
        )
    } else {
        this
    }
}
